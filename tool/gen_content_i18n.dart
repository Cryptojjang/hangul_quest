/// Compiles lib/l10n/content/content_<code>.json (all except _en) into
/// lib/core/data/content_translations.g.dart so lookups are synchronous.
///
///   dart run tool/gen_content_i18n.dart
// ignore_for_file: avoid_print
library;

import 'dart:convert';
import 'dart:io';

void main() {
  final dir = Directory('lib/l10n/content');
  final files = dir
      .listSync()
      .whereType<File>()
      .where((f) => RegExp(r'content_(\w+)\.json$').hasMatch(f.path))
      .where((f) => !f.path.endsWith('content_en.json'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_content_i18n.dart from '
        'lib/l10n/content/*.json.')
    ..writeln('// Do not edit by hand — edit the JSON and re-run the tool.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln('const Map<String, Map<String, String>> contentTranslations = {');
  for (final f in files) {
    final code = RegExp(r'content_(\w+)\.json$').firstMatch(f.path)!.group(1)!;
    final map =
        (jsonDecode(f.readAsStringSync()) as Map).cast<String, String>();
    b.writeln("  '$code': {");
    for (final e in map.entries) {
      b.writeln('    ${jsonEncode(e.key)}: ${_dartString(e.value)},');
    }
    b.writeln('  },');
    print('$code: ${map.length} strings');
  }
  b.writeln('};');
  File('lib/core/data/content_translations.g.dart')
      .writeAsStringSync(b.toString());
}

/// JSON string syntax is valid Dart once `$` is escaped.
String _dartString(String s) => jsonEncode(s).replaceAll(r'$', r'\$');
